export function canonicalTech(name: string): string {
  const v = name.trim().replace(/\s+/g, ' ');
  return SYNONYMS[v.toLowerCase()] ?? v;
}

/** Canonicalise and dedupe (case-insensitive), keeping first-seen order. */
export function normalizeTechList(items: readonly string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of items) {
    const v = canonicalTech(raw);
    if (!v || seen.has(v.toLowerCase())) continue;
    seen.add(v.toLowerCase());
    out.push(v);
  }
  return out;
}
